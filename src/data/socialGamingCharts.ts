function history(values: number[]): RankingEntity["history"] {
  const labels = ["D-6", "D-5", "D-4", "D-3", "D-2", "D-1", "오늘"];
  return values.map((v, i) => ({ t: labels[i] ?? `${i}`, v }));
}

function products(rows: AffiliateProduct[]): AffiliateProduct[] {
  return rows;
}

function entity(
  partial: Omit<RankingEntity, "history" | "sparkline"> & { sparkline: number[] },
): RankingEntity {
  return { ...partial, history: history(partial.sparkline) };
}

